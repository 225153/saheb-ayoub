/* ── Cart drawer ── */
function renderCartDrawer() {
  if (state.cart.length === 0) {
    cartItemsContainer.innerHTML = `<div class="empty-state" style="margin:20px 0;"><i class="fa-solid fa-bag-shopping empty-icon"></i><p class="body-md text-muted">${t("cart_empty")}</p></div>`;
    cartSubtotal.textContent = "$0.00"; checkoutTotal.textContent = "$0.00"; return;
  }
  let subtotal = 0;
  cartItemsContainer.innerHTML = state.cart.map((item) => {
    const p = productCatalog.find((x) => x.id === item.id); if (!p) return "";
    const total = p.price * item.qty; subtotal += total;
    return `<div class="cart-item">
      <img src="${p.image}" class="cart-item-img" alt="${loc(p).title}">
      <div class="cart-item-details">
        <span class="cart-item-title">${loc(p).title}</span>
        <span class="label-sm text-sage">${t("finish_" + item.finish)}</span>
        <span class="cart-item-price">$${p.price} &times; ${item.qty}</span>
        <div class="cart-item-controls">
          <span class="body-md text-flour">$${total}</span>
          <button class="remove-item-btn" onclick="removeFromCart('${item.id}')"><i class="fa-solid fa-trash-can"></i> ${t("remove")}</button>
        </div>
      </div>
    </div>`;
  }).join("");
  cartSubtotal.textContent = `$${subtotal}`; checkoutTotal.textContent = `$${subtotal}`;
}
window.removeFromCart = function (id) { state.cart = state.cart.filter((i) => i.id !== id); updateHeaderBadges(); renderCartDrawer(); showToast(t("toast_removed_bag")); };
function openCartDrawer() { renderCartDrawer(); cartDrawer.classList.add("active"); cartDrawerOverlay.classList.remove("hidden"); }
function closeCartDrawer() { cartDrawer.classList.remove("active"); cartDrawerOverlay.classList.add("hidden"); }

/* ── Toasts ── */
function showToast(msg) {
  const toast = document.createElement("div");
  toast.className = "toast";
  toast.innerHTML = `<i class="fa-solid fa-sparkles"></i> <span>${msg}</span>`;
  toastContainer.appendChild(toast);
  setTimeout(() => { toast.style.opacity = "0"; toast.style.transform = "translateX(100%)"; setTimeout(() => toast.remove(), 300); }, 3000);
}

